// Exports strongly-typed ABIs from the Foundry build output into the backend and the frontend.
//   node scripts/export-abis.mjs        (run `forge build` first)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = (name) => resolve(root, 'contracts/out', `${name}.sol`, `${name}.json`)

const contracts = [
  ['registryAbi', 'AlibiIdentityRegistry'],
  ['escrowAbi', 'AlibiCreditEscrow'],
  ['routerAbi', 'AlibiSlashingRouter'],
  ['vaultAbi', 'AlibiGatedVault'],
  ['verifierAbi', 'Eip712AttestationVerifier'],
]

let body = '// AUTO-GENERATED by scripts/export-abis.mjs from the Foundry build. Do not edit by hand.\n\n'
for (const [exportName, contractName] of contracts) {
  const artifact = JSON.parse(readFileSync(out(contractName), 'utf8'))
  body += `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n\n`
}

for (const target of ['backend/src/abi.ts', 'frontend/src/abi/index.ts']) {
  const file = resolve(root, target)
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, body)
  console.log('wrote', target)
}
